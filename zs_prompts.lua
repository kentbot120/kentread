local M = {}

M.WRITE = [[你要把一本书讲给没读过它的人：让他知道书里具体发生了什么、论证了什么，看清各部分为什么写在一起，并跟着经历原来的理解怎样被事实、事件和后果一步步改变。下面给你全书原文，【】里是章节标题。

动笔前先想清楚：
1. 核心理解：读者原来怎样看这个问题，书中哪些内容让这种理解需要补充或改变
2. 各部分的关系：不同方法、事件、人物或主线各自完成什么，它们怎样依赖、补充、对照或限制彼此。「都在谈同一个主题」不算关系
3. 作者的关切：从书中反复追问的东西、取舍和结尾看，作者最想纠正什么、保留什么。以文本为据，不替作者编造
4. 结构：选原书充分展开、能经历多次变化的线索：一个问题、人物、关系或模型；需要多条主线的书，保留它们，说明在哪里相遇。分 4 到 7 节，标题写成读者正在面对的处境或问题，不写成章节名或知识点名。最后一节固定为「读完后留下什么」

怎样写：
- 从读者能理解的处境开始，让原来的判断先有成立的理由，再让事实和后果出现
- 让一个念头走完。同一个对象还能推进时继续展开，不要每段换一个知识点、配一个例子
- 让变化看得见：原来接受哪句话，现在接受哪句话，新增的条件改变了什么。只写「理解加深了」不算
- 用问题的缺口拉动阅读：一个答案里还没解释的词、没交代的条件，就是下一步的入口。问题提出后，至少隔一句再回答
- 新问题出现、旧判断被推翻、关键概念第一次命名的地方用短句；展开论证时句子可以长
- 术语等读者感到需要它时才出现
- 保留原书具体的人物、案例、数据和原话。原书没有的不编；自己设想的情景用「假如」「想象一下」引出
- 不用「此外」「接下来」「首先、其次」串联内容，联系要在内容里成立
- 不写书籍简介，不预告「本文将讲」，不在段尾总结道理
- 只在关系、层级、流程、对照靠文字难以保持时画图，箭头的含义（因果、先后还是支持）要一致
- 最后一节「读完后留下什么」只写一个短段落，一到四句，收拢前文已经形成的理解，不加新内容

输出格式：
- 只输出 HTML 片段。不要 markdown，不要代码块标记，不要 <html>、<head>、<body>
- 每节用 <h1>，正文用 <p>，强调用 <b>，原话用 <blockquote>
- 需要图时直接写内联 <svg>：viewBox 宽 600，高不超过 800；只用黑、白、灰；文字 font-size 不小于 18，一个汉字的宽度约等于 font-size，框要比文字宽；每个框里不超过 8 个字；箭头用 marker；不用 foreignObject，不指定字体。图后紧接一段话，告诉读者怎样读这张图、能看出什么
- 全文 5000 到 8000 字]]

return M
